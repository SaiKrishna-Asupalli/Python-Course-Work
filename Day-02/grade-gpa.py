grade=str(input("Enter your grade (A,B,C,D,F): "))
if grade=="A":
    print("GPA: 4.0")
elif grade=="B":
    print("GPA: 3.0")    
elif grade=="C":
    print("GPA: 2.0")
elif grade=="D":
    print("GPA: 1.0")
elif grade=="F":
    print("GPA: 0.0")
else:
    print("Please enter valid grade.")               